import { Loader2 } from 'lucide-react'
import { useEffect, useState } from 'react'
import { useTranslation } from 'react-i18next'
import { toast } from 'sonner'

import { Dialog } from '@/components/dialog'
import { Button } from '@/components/ui/button'
import { Label } from '@/components/ui/label'
import { NativeSelect, NativeSelectOption } from '@/components/ui/native-select'
import { handleServerError } from '@/lib/handle-server-error'

import {
  PLAYGROUND_AUDIO_VOICES,
  PLAYGROUND_GENERATION_ERRORS,
  PLAYGROUND_SPEECH_ERRORS,
} from '../../constants'
import { usePlaygroundGeneration } from '../../hooks'
import type { ModelOption } from '../../types'

interface PlaygroundSpeechDialogProps {
  open: boolean
  onOpenChange: (open: boolean) => void
  /** Text the current message contributes to the speech request. */
  text: string
  group: string
  models: ModelOption[]
  /**
   * Caches the generated bytes on the conversation. The caller owns the
   * message/version the audio belongs to, so it persists the reference there.
   */
  onSave: (blob: Blob) => Promise<void>
}

/**
 * Reads one message aloud through the /pg audio route and offers to keep the
 * generated audio on the conversation. Generation is billed by the ordinary
 * relay pipeline like any other request; saving only stores the result.
 */
export function PlaygroundSpeechDialog(props: PlaygroundSpeechDialogProps) {
  const { t } = useTranslation()
  const generation = usePlaygroundGeneration()
  const [model, setModel] = useState('')
  const [voice, setVoice] = useState<string>(PLAYGROUND_AUDIO_VOICES[0])
  const [audio, setAudio] = useState<{ blob: Blob; url: string } | null>(null)
  const [isSaving, setIsSaving] = useState(false)

  useEffect(() => {
    const firstModel = props.models[0]?.value ?? ''
    if (!model && firstModel) setModel(firstModel)
  }, [model, props.models])

  // Moving to another message drops the previous take; the cleanup releases
  // its object URL exactly once.
  useEffect(() => {
    setAudio(null)
  }, [props.open, props.text])

  useEffect(() => {
    return () => {
      if (audio) URL.revokeObjectURL(audio.url)
    }
  }, [audio])

  const trimmedText = props.text.trim()
  const canGenerate =
    !generation.audio.isPending && model.trim() !== '' && trimmedText !== ''

  const handleGenerate = async () => {
    if (!canGenerate) return
    try {
      const blob = await generation.audio.mutateAsync({
        model: model.trim(),
        text: trimmedText,
        group: props.group,
        voice,
      })
      setAudio({ blob, url: URL.createObjectURL(blob) })
    } catch (error) {
      handleServerError(error, t(PLAYGROUND_GENERATION_ERRORS.AUDIO_FAILED))
    }
  }

  const handleSave = async () => {
    if (!audio || isSaving) return
    setIsSaving(true)
    try {
      await props.onSave(audio.blob)
      toast.success(t('Audio saved to the conversation'))
      props.onOpenChange(false)
    } catch (error) {
      handleServerError(error, t(PLAYGROUND_SPEECH_ERRORS.SAVE_FAILED))
    } finally {
      setIsSaving(false)
    }
  }

  return (
    <Dialog
      contentHeight='auto'
      description={t(
        'Speech is generated through the workspace relay and billed like any other request.'
      )}
      footer={
        <>
          <Button
            disabled={isSaving}
            onClick={() => props.onOpenChange(false)}
            type='button'
            variant='outline'
          >
            {t('Close')}
          </Button>
          <Button
            disabled={!audio || isSaving}
            onClick={() => void handleSave()}
            type='button'
          >
            {isSaving ? (
              <Loader2 aria-hidden='true' className='animate-spin' />
            ) : null}
            {t('Save to conversation')}
          </Button>
        </>
      }
      onOpenChange={props.onOpenChange}
      open={props.open}
      title={t('Read aloud')}
    >
      <div className='grid gap-3'>
        <div className='grid gap-2'>
          <Label htmlFor='playground-speech-model'>{t('Model')}</Label>
          <NativeSelect
            disabled={generation.audio.isPending || props.models.length === 0}
            id='playground-speech-model'
            onChange={(event) => setModel(event.target.value)}
            value={model}
          >
            {props.models.length === 0 ? (
              <NativeSelectOption value=''>
                {t('No models available')}
              </NativeSelectOption>
            ) : null}
            {props.models.map((option) => (
              <NativeSelectOption key={option.value} value={option.value}>
                {option.label}
              </NativeSelectOption>
            ))}
          </NativeSelect>
        </div>

        <div className='grid gap-2'>
          <Label htmlFor='playground-speech-voice'>{t('Voice')}</Label>
          <NativeSelect
            disabled={generation.audio.isPending}
            id='playground-speech-voice'
            onChange={(event) => setVoice(event.target.value)}
            value={voice}
          >
            {PLAYGROUND_AUDIO_VOICES.map((option) => (
              <NativeSelectOption key={option} value={option}>
                {option}
              </NativeSelectOption>
            ))}
          </NativeSelect>
        </div>

        <Button
          disabled={!canGenerate}
          onClick={() => void handleGenerate()}
          type='button'
        >
          {generation.audio.isPending ? (
            <Loader2 aria-hidden='true' className='animate-spin' />
          ) : null}
          {generation.audio.isPending ? t('Generating...') : t('Generate')}
        </Button>

        {audio ? (
          <audio
            aria-label={t('Generated audio')}
            className='w-full'
            controls
            src={audio.url}
          />
        ) : null}
      </div>
    </Dialog>
  )
}
