import * as katex from 'katex'

/**
 * KaTeX is loaded with its stylesheet on first use. The stylesheet is 270 KiB
 * and only chats that actually contain formulas should pay for it, so it is
 * imported dynamically rather than at module scope.
 */
let stylesheetPromise: Promise<void> | null = null

export function ensureKatexStylesheet(): Promise<void> {
  if (stylesheetPromise == null) {
    stylesheetPromise = import('katex/dist/katex.min.css').then(
      () => undefined,
      () => undefined
    )
  }
  return stylesheetPromise
}

/** Strip delimiters the parser may have left on a math node. */
function normalizeMathSource(source: string): string {
  return source
    .trim()
    .replace(/^\\\(/, '')
    .replace(/\\\)$/, '')
    .replace(/^\\\[/, '')
    .replace(/\\\]$/, '')
}

/**
 * Render a TeX source to KaTeX HTML. The output is generated by KaTeX from
 * page content, never raw model output, and `trust: false` blocks the
 * `\href`/`\url` commands that could inject a scheme.
 */
export function renderLatexHtml(
  source: string,
  displayMode: boolean
): string | null {
  const tex = normalizeMathSource(source)
  if (tex === '') {
    return null
  }
  try {
    return katex.renderToString(tex, {
      displayMode,
      output: 'htmlAndMathml',
      throwOnError: false,
      strict: 'ignore',
      trust: false,
    })
  } catch {
    // A malformed formula must never take the whole message down.
    return null
  }
}
